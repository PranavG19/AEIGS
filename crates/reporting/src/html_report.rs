/// Configuration for the standalone HTML report generator.
pub struct HtmlReportConfig {
    pub title: String,
    pub tool_version: String,
    pub include_attack_chain: bool,
    pub include_remediation: bool,
}

impl Default for HtmlReportConfig {
    fn default() -> Self {
        Self {
            title: "AEGIS Security Scan Report".to_string(),
            tool_version: "0.1.0".to_string(),
            include_attack_chain: true,
            include_remediation: true,
        }
    }
}

/// Severity rating string from composite score.
///
/// Thresholds mirror `report_format::severity_rating`:
/// - `>=70` → Critical
/// - `>=40` → High
/// - `>=20` → Medium
/// - else   → Low
pub fn severity_rating(score: f64) -> &'static str {
    if score >= 70.0 {
        "Critical"
    } else if score >= 40.0 {
        "High"
    } else if score >= 20.0 {
        "Medium"
    } else {
        "Low"
    }
}

/// Map a severity rating label to a hex colour.
pub fn severity_color(rating: &str) -> &'static str {
    match rating {
        "Critical" => "#ff4444",
        "High" => "#ff8c00",
        "Medium" => "#ffd700",
        "Low" => "#44ff44",
        _ => "#888888",
    }
}

/// Escape the five characters that are meaningful in HTML.
pub fn html_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for ch in s.chars() {
        match ch {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#x27;"),
            _ => out.push(ch),
        }
    }
    out
}

/// Produce a complete, self-contained HTML document for the scan results.
pub fn generate_html_report(
    findings: &[SarifFinding],
    config: &HtmlReportConfig,
    metadata: Option<&ReportMetadata>,
    defense_summary: Option<&DefenseSummary>,
) -> String {
    let css = generate_css();
    let executive_summary = generate_executive_summary(findings, metadata, defense_summary);
    let finding_cards = generate_finding_cards(findings, config.include_remediation);
    let findings_table = generate_findings_table(findings);
    let attack_chain_section = if config.include_attack_chain {
        generate_attack_chain_svg(findings)
    } else {
        String::new()
    };
    let js = generate_js();

    let escaped_title = html_escape(&config.title);

    format!(
        r#"<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>{escaped_title}</title>
<style>
{css}
</style>
</head>
<body>
<header>
<h1>{escaped_title}</h1>
<p class="tool-version">Generated by AEGIS v{version}</p>
</header>
<main>
{executive_summary}
{attack_chain_section}
<section id="findings-table-section">
<h2>Findings Table</h2>
{findings_table}
</section>
<section id="finding-cards-section">
<h2>Finding Details</h2>
{finding_cards}
</section>
</main>
<footer>
<p>Report generated by AEGIS Security Scanner v{version}</p>
</footer>
<script>
{js}
</script>
</body>
</html>"#,
        escaped_title = escaped_title,
        version = html_escape(&config.tool_version),
        css = css,
        executive_summary = executive_summary,
        attack_chain_section = attack_chain_section,
        finding_cards = finding_cards,
        findings_table = findings_table,
        js = js,
    )
}

