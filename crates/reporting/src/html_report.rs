fn generate_js() -> String {
    r#"
(function() {
    /* Collapsible finding cards */
    document.querySelectorAll('.finding-card-header').forEach(function(header) {
        header.addEventListener('click', function() {
            header.parentElement.classList.toggle('open');
        });
    });

    /* Sortable table columns */
    document.querySelectorAll('table.findings-table th[data-sort]').forEach(function(th) {
        th.addEventListener('click', function() {
            var table = th.closest('table');
            var tbody = table.querySelector('tbody');
            var rows = Array.from(tbody.querySelectorAll('tr'));
            var colIndex = parseInt(th.getAttribute('data-sort'), 10);
            var isNumeric = th.hasAttribute('data-numeric');
            var ascending = th.getAttribute('data-dir') !== 'asc';
            th.setAttribute('data-dir', ascending ? 'asc' : 'desc');

            rows.sort(function(a, b) {
                var aText = a.cells[colIndex].textContent.trim();
                var bText = b.cells[colIndex].textContent.trim();
                if (isNumeric) {
                    return ascending
                        ? parseFloat(aText) - parseFloat(bText)
                        : parseFloat(bText) - parseFloat(aText);
                }
                return ascending
                    ? aText.localeCompare(bText)
                    : bText.localeCompare(aText);
            });

            rows.forEach(function(row) { tbody.appendChild(row); });
        });
    });

    /* Filter bar */
    var filterInput = document.getElementById('finding-filter');
    var severitySelect = document.getElementById('severity-filter');

    function applyFilters() {
        var text = (filterInput ? filterInput.value : '').toLowerCase();
        var severity = severitySelect ? severitySelect.value : '';
        var tbody = document.querySelector('table.findings-table tbody');
        if (!tbody) return;
        Array.from(tbody.querySelectorAll('tr')).forEach(function(row) {
            var rowText = row.textContent.toLowerCase();
            var rowSeverity = row.getAttribute('data-severity') || '';
            var matchText = text === '' || rowText.indexOf(text) !== -1;
            var matchSeverity = severity === '' || rowSeverity === severity;
            row.style.display = (matchText && matchSeverity) ? '' : 'none';
        });
    }

    if (filterInput) filterInput.addEventListener('input', applyFilters);
    if (severitySelect) severitySelect.addEventListener('change', applyFilters);
})();
"#
    .to_string()
}

fn generate_executive_summary(
    findings: &[SarifFinding],
    metadata: Option<&ReportMetadata>,
    defense_summary: Option<&DefenseSummary>,
) -> String {
    let mut critical = 0usize;
    let mut high = 0usize;
    let mut medium = 0usize;
    let mut low = 0usize;

    for f in findings {
        match severity_rating(f.composite_score) {
            "Critical" => critical += 1,
            "High" => high += 1,
            "Medium" => medium += 1,
            _ => low += 1,
        }
    }

    let total = findings.len();
    let max_composite = findings
        .iter()
        .map(|f| f.composite_score)
        .fold(0.0_f64, f64::max);
    let overall_rating = severity_rating(max_composite);
    let overall_color = severity_color(overall_rating);

    let meta_section = metadata
        .map(|m| {
            format!(
                r#"<div class="summary-card">
    <div class="count" style="font-size:1rem;">{target}</div>
    <div class="label">Target</div>
</div>
<div class="summary-card">
    <div class="count">{duration:.1}s</div>
    <div class="label">Scan Duration</div>
</div>
<div class="summary-card">
    <div class="count">{phases}</div>
    <div class="label">Phases Completed</div>
</div>"#,
                target = html_escape(&m.target_url),
                duration = m.total_duration_secs,
                phases = m.phases_completed,
            )
        })
        .unwrap_or_default();

    let defense_section = defense_summary
        .map(|ds| {
            let waf_indicator = if ds.has_waf {
                "indicator-active"
            } else {
                "indicator-inactive"
            };
            let rl_indicator = if ds.has_rate_limiting {
                "indicator-active"
            } else {
                "indicator-inactive"
            };
            let bd_indicator = if ds.has_bot_detection {
                "indicator-active"
            } else {
                "indicator-inactive"
            };
            let waf_label = ds
                .waf_vendor
                .as_ref()
                .map(|v| format!("WAF ({})", html_escape(v)))
                .unwrap_or_else(|| "WAF".to_string());

            format!(
                r#"<div class="defense-info">
<h3>Defense Posture</h3>
<div class="defense-item"><span class="indicator {waf_indicator}"></span> {waf_label}</div>
<div class="defense-item"><span class="indicator {rl_indicator}"></span> Rate Limiting</div>
<div class="defense-item"><span class="indicator {bd_indicator}"></span> Bot Detection</div>
</div>"#,
                waf_indicator = waf_indicator,
                waf_label = waf_label,
                rl_indicator = rl_indicator,
                bd_indicator = bd_indicator,
            )
        })
        .unwrap_or_default();

    format!(
        r#"<section id="executive-summary">
<h2>Executive Summary</h2>
<div class="summary-grid">
<div class="summary-card">
    <div class="count">{total}</div>
    <div class="label">Total Findings</div>
</div>
<div class="summary-card">
    <div class="count" style="color:{critical_color};">{critical}</div>
    <div class="label">Critical</div>
</div>
<div class="summary-card">
    <div class="count" style="color:{high_color};">{high}</div>
    <div class="label">High</div>
</div>
<div class="summary-card">
    <div class="count" style="color:{medium_color};">{medium}</div>
    <div class="label">Medium</div>
</div>
<div class="summary-card">
    <div class="count" style="color:{low_color};">{low}</div>
    <div class="label">Low</div>
</div>
<div class="summary-card">
    <div class="count" style="color:{overall_color};">{overall_rating}</div>
    <div class="label">Overall Risk</div>
</div>
{meta_section}
</div>
{defense_section}
</section>"#,
        total = total,
        critical = critical,
        critical_color = severity_color("Critical"),
        high = high,
        high_color = severity_color("High"),
        medium = medium,
        medium_color = severity_color("Medium"),
        low = low,
        low_color = severity_color("Low"),
        overall_rating = overall_rating,
        overall_color = overall_color,
        meta_section = meta_section,
        defense_section = defense_section,
    )
}

fn generate_finding_cards(findings: &[SarifFinding], include_remediation: bool) -> String {
    if findings.is_empty() {
        return "<p>No findings to display.</p>".to_string();
    }

    let mut cards = String::new();
    for (idx, f) in findings.iter().enumerate() {
        let rating = severity_rating(f.composite_score);
        let badge_class = match rating {
            "Critical" => "badge-critical",
            "High" => "badge-high",
            "Medium" => "badge-medium",
            _ => "badge-low",
        };
        let cwe_text = f
            .vulnerability_class
            .as_ref()
            .map(|vc| cwe_for(vc).to_string())
            .unwrap_or_default();
        let attack_text = f
            .vulnerability_class
            .as_ref()
            .map(|vc| attack_technique_for(vc).to_string())
            .unwrap_or_default();
        let remediation_html = if include_remediation {
            f.vulnerability_class
                .as_ref()
                .map(|vc| {
                    format!(
                        r#"<div class="remediation-box">
<div class="detail-label">Remediation</div>
<div class="detail-value">{}</div>
</div>"#,
                        html_escape(remediation_for(vc)),
                    )
                })
                .unwrap_or_default()
        } else {
            String::new()
        };

        let endpoint_html = f
            .endpoint
            .as_ref()
            .map(|ep| {
                format!(
                    r#"<div class="finding-detail">
<span class="detail-label">Endpoint:</span>
<span class="detail-value">{method} {ep}</span>
</div>"#,
                    method = html_escape(f.http_method.as_deref().unwrap_or("GET")),
                    ep = html_escape(ep),
                )
            })
            .unwrap_or_default();

        let parameter_html = f
            .parameter_name
            .as_ref()
            .map(|p| {
                format!(
                    r#"<div class="finding-detail">
<span class="detail-label">Parameter:</span>
<span class="detail-value">{}</span>
</div>"#,
                    html_escape(p),
                )
            })
            .unwrap_or_default();

        let evidence_html = f
            .evidence_level
            .as_ref()
            .map(|e| {
                format!(
                    r#"<div class="finding-detail">
<span class="detail-label">Evidence Level:</span>
<span class="detail-value">{}</span>
</div>"#,
                    html_escape(e),
                )
            })
            .unwrap_or_default();

        let cve_html = f
            .cve_id
            .as_ref()
            .map(|cve| {
                format!(
                    r#"<div class="finding-detail">
<span class="detail-label">CVE:</span>
<span class="detail-value"><a href="https://nvd.nist.gov/vuln/detail/{cve}" style="color:var(--accent);">{cve}</a></span>
</div>"#,
                    cve = html_escape(cve),
                )
            })
            .unwrap_or_default();

        let vuln_class_html = f
            .vulnerability_class
            .as_ref()
            .map(|vc| {
                format!(
                    r#"<div class="finding-detail">
<span class="detail-label">Vulnerability Class:</span>
<span class="detail-value">{}</span>
</div>"#,
                    html_escape(&format!("{vc}")),
                )
            })
            .unwrap_or_default();

        let defense_html = f
            .defense_context
            .as_ref()
            .map(|dc| {
                let mut parts = Vec::new();
                if !dc.defenses_detected.is_empty() {
                    parts.push(format!(
                        "Defenses detected: {}",
                        dc.defenses_detected
                            .iter()
                            .map(|d| html_escape(d))
                            .collect::<Vec<_>>()
                            .join(", ")
                    ));
                }
                if dc.exploitable_despite_waf {
                    parts.push("Exploitable despite WAF".to_string());
                }
                if let Some(tech) = &dc.evasion_technique {
                    parts.push(format!("Evasion: {}", html_escape(tech)));
                }
                if parts.is_empty() {
                    String::new()
                } else {
                    format!(
                        r#"<div class="finding-detail">
<span class="detail-label">Defense Context:</span>
<span class="detail-value">{}</span>
</div>"#,
                        parts.join(" | "),
                    )
                }
            })
            .unwrap_or_default();

        cards.push_str(&format!(
            r#"<div class="finding-card" id="finding-{idx}">
<div class="finding-card-header">
    <span>
        <span class="rule-id">{rule_id}</span>
        — {message_short}
    </span>
    <span class="badge {badge_class}">{rating}</span>
</div>
<div class="finding-card-body">
    <div class="finding-detail">
        <span class="detail-label">Message:</span>
        <span class="detail-value">{message}</span>
    </div>
    <div class="finding-detail">
        <span class="detail-label">Severity / Confidence / Composite:</span>
        <span class="detail-value">{severity:.1} / {confidence:.1} / {composite:.1}</span>
    </div>
    <div class="finding-detail">
        <span class="detail-label">Level:</span>
        <span class="detail-value">{level}</span>
    </div>
    {vuln_class_html}
    {endpoint_html}
    {parameter_html}
    {evidence_html}
    {cve_html}
    {cwe_line}
    {attack_line}
    {defense_html}
    {remediation_html}
</div>
</div>
"#,
            idx = idx,
            rule_id = html_escape(&f.rule_id),
            message_short = html_escape(&truncate_message(&f.message, 80)),
            badge_class = badge_class,
            rating = rating,
            message = html_escape(&f.message),
            severity = f.severity,
            confidence = f.confidence,
            composite = f.composite_score,
            level = f.level.as_str(),
            vuln_class_html = vuln_class_html,
            endpoint_html = endpoint_html,
            parameter_html = parameter_html,
            evidence_html = evidence_html,
            cve_html = cve_html,
            cwe_line = if cwe_text.is_empty() {
                String::new()
            } else {
                format!(
                    r#"<div class="finding-detail"><span class="detail-label">CWE:</span> <span class="detail-value">{cwe_text}</span></div>"#,
                    cwe_text = html_escape(&cwe_text),
                )
            },
            attack_line = if attack_text.is_empty() {
                String::new()
            } else {
                format!(
                    r#"<div class="finding-detail"><span class="detail-label">ATT&amp;CK:</span> <span class="detail-value">{attack_text}</span></div>"#,
                    attack_text = html_escape(&attack_text),
                )
            },
            defense_html = defense_html,
            remediation_html = remediation_html,
        ));
    }

    cards
}

fn truncate_message(msg: &str, max_len: usize) -> String {
    if msg.len() <= max_len {
        msg.to_string()
    } else {
        let mut end = max_len;
        while end > 0 && !msg.is_char_boundary(end) {
            end -= 1;
        }
        format!("{}…", &msg[..end])
    }
}

