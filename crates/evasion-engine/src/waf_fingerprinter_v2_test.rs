use super::waf_fingerprinter_v2::*;
use std::collections::HashMap;

fn response_with_headers(headers: Vec<(&str, &str)>) -> ResponseFingerprint {
    ResponseFingerprint {
        status_code: 403,
        headers: headers
            .into_iter()
            .map(|(k, v)| (k.to_string(), v.to_string()))
            .collect(),
        body_snippet: String::new(),
    }
}

fn response_with_body(body: &str) -> ResponseFingerprint {
    ResponseFingerprint {
        status_code: 403,
        headers: HashMap::new(),
        body_snippet: body.to_string(),
    }
}

