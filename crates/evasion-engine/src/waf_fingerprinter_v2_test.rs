#[test]
fn test_multi_response_fingerprinting() {
    let fp = WafFingerprinterV2::new();
    let responses = vec![
        response_with_headers(vec![("cf-ray", "abc123")]),
        response_with_headers(vec![("server", "cloudflare")]),
        response_with_body("Attention Required! | Cloudflare"),
    ];
    let result = fp.fingerprint_multi(&responses);
    assert_eq!(result.primary_vendor, WafVendor::Cloudflare);
    assert!(result.confidence > 0.5);
}

#[test]
fn test_get_bypass_strategy() {
    let fp = WafFingerprinterV2::new();
    let strat = fp.get_bypass_strategy(WafVendor::Cloudflare);
    assert!(strat.is_some());
    let strat = strat.unwrap();
    assert!(!strat.preferred_encodings.is_empty());
    assert!(strat.timing_advice_ms.0 < strat.timing_advice_ms.1);
}

